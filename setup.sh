#!/usr/bin/env bash
# Create ./config and ./vpn.conf from the .ovpn profile you download from the
# AWS Client VPN console (or get from your admin).
#   Usage: ./setup.sh path/to/profile.ovpn
set -euo pipefail
cd "$(dirname "$0")"

[ $# -eq 1 ] && [ -f "$1" ] || { echo "usage: $0 <profile.ovpn>"; exit 2; }

host=$(awk '$1 == "remote" {print $2; exit}' "$1")
port=$(awk '$1 == "remote" {print $3; exit}' "$1")
proto=$(awk '$1 == "proto" {print $2; exit}' "$1")
[ -n "$host" ] || { echo "No 'remote' line found in $1"; exit 1; }

grep -q '^auth-federate' "$1" || \
  echo "note: $1 has no 'auth-federate' line - this endpoint may not use SAML"

# Strip lines the scripts handle themselves: the remote (passed on the command
# line so a random gateway hostname can be resolved first) and the auth lines
# (credentials are injected dynamically with the SAML response).
grep -vE '^(remote|remote-random-hostname|auth-user-pass|auth-federate|auth-retry)([[:space:]]|$)' "$1" > vpn.conf

cat > config <<EOF
# Generated by setup.sh from $(basename "$1")
VPN_HOST="$host"
PORT="${port:-443}"
PROTO="${proto:-udp}"
# Name shown in desktop notifications.
VPN_NAME="AWS VPN"
EOF

echo "Wrote ./config (VPN_HOST=$host) and ./vpn.conf"
echo "Next: ./build.sh && ./install.sh"
